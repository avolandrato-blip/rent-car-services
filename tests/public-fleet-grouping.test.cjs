const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { individualFleetVehicles, formatVehicleUid, countAvailability } = require('../fleet-utils.js');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');

function car(id, uid, fleet_group = 'Kia Morning') {
  return { id, uid, name: 'Kia Morning', model: 'Morning', fleet_group, status: 'available', price_per_day: 150000 };
}

test('le catalogue client affiche chaque voiture individuellement même si les noms et groupes sont identiques', () => {
  const items = individualFleetVehicles([car('vehicle-1', 7), car('vehicle-2', 8)]);
  assert.equal(items.length, 2);
  assert.deepEqual(items.map(item => item.id), ['vehicle-1', 'vehicle-2']);
  assert.deepEqual(items.map(item => item.capacity), [1, 1]);
  assert.deepEqual(items.map(item => item.displayName), ['Kia Morning', 'Kia Morning']);
  assert.deepEqual(items.map(item => item.uid), [7, 8]);
  assert.equal(formatVehicleUid(items[0].vehicle), 'UID-000007');
  assert.equal(formatVehicleUid(items[1].vehicle), 'UID-000008');
});

test('les cartes client, la recherche et les choix de réservation exposent le UID tout en conservant l’UUID véhicule', () => {
  const script = read('script.js');
  assert.match(script, /individualFleetVehicles\(normalized\)/);
  assert.match(script, /individualFleetVehicles\(bookingVehicles\)/);
  assert.match(script, /data-fleet-id=\"\$\{fleetId\}\"/);
  assert.match(script, /class=\"car-uid\"/);
  assert.match(script, /car\.model \|\| ''\} \$\{car\.uid \|\| ''\}/);
  assert.match(script, /\$\{name\} — \$\{uid\} — \$\{price\}/);
  assert.match(script, /owner_whatsapp_enabled,uid/);
  assert.doesNotMatch(script, /groupFleetVehicles\((normalized|bookingVehicles)\)/);
  assert.match(read('index.html'), /20261111-individual-vehicle-uid/);
});

test('le catalogue rend les voitures si le filtre transmission est absent', () => {
  const script = read('script.js');
  assert.match(script, /const transmissionFilter = document\.getElementById\('fleet-transmission'\)\?\.value \|\| 'all'/);
  assert.match(script, /transmissionFilter === 'all' \|\| car\.transmission === transmissionFilter/);
  assert.doesNotMatch(script, /\btransmission === 'all'/);
  assert.match(script, /fleet-sort','fleet-transmission'/);
  assert.match(read('index.html'), /script\.js\?v=20261112-fix-empty-catalogue/);
});

test('les réservations et disponibilités portent sur une seule unité physique par UID', () => {
  const items = individualFleetVehicles([car('vehicle-1', 17), car('vehicle-2', 18)]);
  const result = countAvailability(items[0], '2026-11-12T07:00:00Z', '2026-11-13T07:00:00Z', [
    { vehicle_id: 'vehicle-1', start_at: '2026-11-12T08:00:00Z', end_at: '2026-11-12T12:00:00Z', status: 'reserved' },
  ], []);
  assert.equal(result.totalCount, 1);
  assert.equal(result.availableCount, 0);
  assert.equal(items[1].units[0].id, 'vehicle-2');
  assert.match(read('enhancements.js'), /vehicle_id: unit\.id/);
});

test('la vue publique ajoute un UID unique et retire le groupe du catalogue client', () => {
  const migration = read('supabase/migrations/20261111160731_individual_public_fleet_uid.sql');
  assert.match(migration, /uid bigint GENERATED BY DEFAULT AS IDENTITY/i);
  assert.match(migration, /vehicles_uid_unique_idx/);
  assert.match(migration, /DROP VIEW IF EXISTS public\.public_fleet_vehicles/i);
  assert.match(migration, /GRANT SELECT ON public\.public_fleet_vehicles TO anon, authenticated/i);
  assert.match(migration, /WHERE status = 'available'/i);
  assert.doesNotMatch(migration.match(/CREATE VIEW public\.public_fleet_vehicles[\s\S]*?FROM public\.vehicles/i)?.[0] || '', /fleet_group/i);
});
