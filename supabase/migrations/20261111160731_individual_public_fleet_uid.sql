-- Identifiant public unique et stable pour distinguer les véhicules ayant le même nom.
ALTER TABLE public.vehicles
  ADD COLUMN IF NOT EXISTS uid bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.vehicles
  ALTER COLUMN uid SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS vehicles_uid_unique_idx
  ON public.vehicles (uid);

-- Le catalogue client expose les unités individuellement et ne publie plus la notion
-- interne de fleet_group. Les voitures hors catalogue restent réservables via les
-- créneaux, mais seules celles publiées disponibles apparaissent dans cette vue.
DROP VIEW IF EXISTS public.public_fleet_vehicles;

CREATE VIEW public.public_fleet_vehicles
WITH (security_invoker = false, security_barrier = true)
AS
SELECT
  id,
  name,
  slug,
  description,
  price_per_day,
  transmission,
  fuel,
  seats,
  status,
  image_urls,
  make,
  model,
  price_12h,
  price_24h,
  driver_mode,
  driver_fee,
  extra_driver_fee,
  CASE
    WHEN owner_whatsapp_enabled THEN owner_phone
    ELSE NULL::text
  END AS owner_phone,
  owner_whatsapp_enabled,
  contract_start_date,
  contract_end_date,
  province_under_150_mode,
  province_under_150_price,
  province_over_150_mode,
  province_over_150_price,
  price_30_100_per_day,
  price_100_200_per_day,
  price_over_200_per_day,
  uid
FROM public.vehicles
WHERE status = 'available'::public.vehicle_status
  AND (contract_end_date IS NULL OR contract_end_date >= (now() AT TIME ZONE 'Indian/Antananarivo')::date);

REVOKE ALL ON public.public_fleet_vehicles FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.public_fleet_vehicles TO anon, authenticated;
